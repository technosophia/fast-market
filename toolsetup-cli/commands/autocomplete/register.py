from __future__ import annotations

import os
import re
from textwrap import dedent

import click
from pathlib import Path

from commands.completion import ShellType
from commands.discovery import discover_fastmarket_commands

# Command names are interpolated into a shell script. Reject anything that
# could break out of a single token.
_SAFE_TOOL_NAME = re.compile(r"[A-Za-z][A-Za-z0-9_-]*\Z")


def _get_config_dir() -> Path:
    """Get XDG config home / fast-market directory."""
    xdg_config = os.environ.get("XDG_CONFIG_HOME", str(Path.home() / ".config"))
    return Path(xdg_config) / "fast-market"


def register():
    """Return the 'autocomplete' command group with configure + list subcommands."""
    @click.group(
        "autocomplete",
        help="Manage shell autocompletion for fast-market CLI tools.",
    )
    def autocomplete_group():
        """Autocompletion management."""
        pass

    @autocomplete_group.command("configure")
    @click.option(
        "--shell",
        "-s",
        type=ShellType(),
        default="bash",
        help="Shell type",
    )
    @click.option("--force", "-f", is_flag=True, help="Regenerate completion files")
    def configure(shell: str, force: bool):
        """Generate shell completion script for all discovered fast-market CLIs."""
        tools = discover_fastmarket_commands()

        config_dir = _get_config_dir()
        completions_dir = config_dir / "completions"
        completions_dir.mkdir(parents=True, exist_ok=True)
        completion_file = completions_dir / f"fast-market.{shell}"

        if completion_file.exists() and not force:
            existing_content = completion_file.read_text().strip()
            desired_lines = _generate_completion_script(shell, tools)
            desired_content = "\n".join(desired_lines).strip()

            if existing_content == desired_content:
                click.echo(f"Completions already configured for: {', '.join(tools)}")
                click.echo(f"File: {completion_file}")
                click.echo("\nTo regenerate (e.g. after adding/removing a *-cli), run with --force")
                return
            else:
                click.echo("Completions file is out of date.")
                click.echo("It contains stale entries (e.g. removed CLIs like tiktok) or is missing newly added CLIs.")
                click.echo(f"File: {completion_file}")
                click.echo("Run with --force to regenerate a clean file for the current set of tools.")
                return

        click.echo(f"Generating completions for: {', '.join(tools)}")

        lines = _generate_completion_script(shell, tools)
        completion_file.write_text("\n".join(lines))

        click.echo(f"\nCompletions saved to: {completion_file}")

        if shell == "bash":
            click.echo("\nAdd this to your ~/.bashrc:")
            click.echo(f"  source {completion_file}")
        elif shell == "zsh":
            click.echo("\nAdd this to your ~/.zshrc:")
            click.echo(f"  source {completion_file}")
        elif shell == "fish":
            click.echo("\nAdd this to your ~/.config/fish/config.fish:")
            click.echo(f"  source {completion_file}")

        click.echo(
            "\nOr run the source command above to enable completions immediately."
        )

    @autocomplete_group.command("list")
    def list_cmd():
        """List all currently discovered fast-market CLI command names."""
        for name in discover_fastmarket_commands():
            click.echo(name)

    return autocomplete_group


def _generate_completion_script(shell: str, tools: list[str]) -> list[str]:
    """Build a shell script that registers Click completions.

    The script must be safe to source from an interactive shell. A raw
    ``eval "$(_{CMD}_COMPLETE=bash_source cmd)"`` executes whatever the
    command prints. On this machine ``browser`` is browser-use, which
    prints a welcome text (and a ``<<'PY'`` example) when stdin is a
    terminal. Eval then launches Chrome.
    """
    safe_tools = [_require_safe_tool_name(tool) for tool in tools]
    header = [
        "# Fast-market shell completions",
        "# Generated by toolsetup autocomplete configure",
        "# Stdin is closed, Python warnings are dropped, and stdout is",
        "# eval'd only when it is a Click completion script.",
        "",
    ]
    if shell == "bash":
        body = _bash_completion_script(safe_tools)
    elif shell == "zsh":
        body = _zsh_completion_script(safe_tools)
    elif shell == "fish":
        body = _fish_completion_script(safe_tools)
    else:
        raise ValueError(
            f"Unsupported shell {shell!r}. Expected one of: bash, zsh, fish."
        )
    return header + body


def _require_safe_tool_name(tool: str) -> str:
    if not isinstance(tool, str) or _SAFE_TOOL_NAME.fullmatch(tool) is None:
        raise ValueError(
            "FAIL LOUDLY: refusing to emit a completion line for unsafe "
            f"command name: {tool!r}"
        )
    return tool


def _bash_completion_script(tools: list[str]) -> list[str]:
    loader = dedent(
        r"""
        _fastmarket_load_completion() {
          local tool="$1"
          local mode="$2"
          local candidate=""
          local shebang=""
          local sig=""
          local out=""

          if command -v pyenv >/dev/null 2>&1; then
            candidate="$(pyenv which "$tool" 2>/dev/null || true)"
          fi
          if [[ -z "$candidate" || ! -x "$candidate" ]]; then
            candidate="$(command -v "$tool" 2>/dev/null || true)"
          fi
          [[ -n "$candidate" && -x "$candidate" ]] || return 0

          # browser-use ships a `browser` command. Sourcing its welcome
          # text is what launches Chrome at shell startup.
          case "$candidate" in
            */browser-use/*) return 0 ;;
          esac

          sig="$(head -c 2 "$candidate" 2>/dev/null || true)"
          [[ "$sig" == "#!" ]] || return 0
          IFS= read -r shebang < "$candidate" || return 0
          if [[ "$shebang" != *python* && "$candidate" != */pyenv/shims/* ]]; then
            return 0
          fi

          out="$(
            PYTHONWARNINGS=ignore \
              env "_${tool^^}_COMPLETE=${mode}" \
              "$candidate" </dev/null 2>/dev/null
          )" || return 0

          case "$mode" in
            bash_source) [[ "$out" == *"complete -"* ]] || return 0 ;;
            *) return 0 ;;
          esac
          eval "$out"
        }
        """
    ).strip("\n")
    lines = loader.splitlines()
    lines.append("")
    lines.extend(
        f"_fastmarket_load_completion {tool} bash_source" for tool in tools
    )
    lines.append("unset -f _fastmarket_load_completion")
    return lines


def _zsh_completion_script(tools: list[str]) -> list[str]:
    loader = dedent(
        r"""
        _fastmarket_load_completion() {
          local tool="$1"
          local mode="$2"
          local candidate=""
          local shebang=""
          local sig=""
          local out=""
          local env_name=""

          if whence -p pyenv >/dev/null 2>&1; then
            candidate="$(pyenv which "$tool" 2>/dev/null || true)"
          fi
          if [[ -z "$candidate" || ! -x "$candidate" ]]; then
            candidate="$(whence -p "$tool" 2>/dev/null || true)"
          fi
          [[ -n "$candidate" && -x "$candidate" ]] || return 0

          case "$candidate" in
            */browser-use/*) return 0 ;;
          esac

          sig="$(head -c 2 "$candidate" 2>/dev/null || true)"
          [[ "$sig" == "#!" ]] || return 0
          IFS= read -r shebang < "$candidate" || return 0
          if [[ "$shebang" != *python* && "$candidate" != */pyenv/shims/* ]]; then
            return 0
          fi

          env_name="_${(U)tool}_COMPLETE"
          out="$(
            PYTHONWARNINGS=ignore \
              env "${env_name}=${mode}" \
              "$candidate" </dev/null 2>/dev/null
          )" || return 0

          [[ "$out" == *"compdef "* ]] || return 0
          eval "$out"
        }
        """
    ).strip("\n")
    lines = loader.splitlines()
    lines.append("")
    lines.extend(
        f"_fastmarket_load_completion {tool} zsh_source" for tool in tools
    )
    lines.append("unfunction _fastmarket_load_completion")
    return lines


def _fish_completion_script(tools: list[str]) -> list[str]:
    loader = dedent(
        r"""
        function _fastmarket_load_completion
            set -l tool $argv[1]
            set -l upper (string upper -- $tool)
            set -l env_name "_"$upper"_COMPLETE"
            set -l candidate ""

            if type -q pyenv
                set candidate (pyenv which $tool 2>/dev/null)
            end
            if test -z "$candidate"; or not test -x "$candidate"
                set candidate (command -v $tool 2>/dev/null)
            end
            if test -z "$candidate"; or not test -x "$candidate"
                return 0
            end
            if string match -q -- '*/browser-use/*' $candidate
                return 0
            end

            set -l sig (head -c 2 $candidate 2>/dev/null)
            if test "$sig" != "#!"
                return 0
            end
            set -l shebang (head -n 1 $candidate 2>/dev/null)
            if not string match -q -- '*python*' $shebang; and not string match -q -- '*/pyenv/shims/*' $candidate
                return 0
            end

            set -l out (
                env PYTHONWARNINGS=ignore "$env_name=fish_source" $candidate </dev/null 2>/dev/null \
                | string collect
            )
            if not string match -q -- '*complete --*' $out
                return 0
            end
            eval $out
        end
        """
    ).strip("\n")
    lines = loader.splitlines()
    lines.append("")
    lines.extend(f"_fastmarket_load_completion {tool}" for tool in tools)
    lines.append("functions -e _fastmarket_load_completion")
    return lines


def get_registered_tools() -> list[str]:
    """Return the live list of discovered fast-market CLI commands."""
    return discover_fastmarket_commands()
